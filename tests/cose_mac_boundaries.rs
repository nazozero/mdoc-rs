//! Security boundaries of the optional, externally keyed DeviceMAC primitive.
//!
//! The server presentation verifier does not enable DeviceMAC. These tests
//! establish only MAC-structure and byte-integrity behavior, not ECDH peer trust,
//! MSO authentication, request-context binding, or complete ISO interoperability.
//!
//! The MAC_structure framing follows RFC 9052 Section 6.3:
//! <https://www.rfc-editor.org/rfc/rfc9052.html#section-6.3>.
//! Expected tags below are independent synthetic vectors, computed using Python
//! standard-library hmac over explicitly framed CBOR; they are not RFC vectors
//! and are never generated by the Rust implementation under test.
//!
//! Reproduce all four tags without coset or nazo-mdoc:
//! ```python
//! import hashlib, hmac
//! key = bytes(range(32))  # Public synthetic vector material, never a deployment key.
//! payload = bytes.fromhex(
//!     "d8185823847444657669636541757468656e7469636174696f6e"
//!     "83f6f6f66474657374d81841a0")
//! def bstr(value):
//!     head = bytes([0x40 + len(value)]) if len(value) < 24 else bytes([0x58, len(value)])
//!     return head + value
//! for protected, aad in [("a10105", b""), ("a10105", b"aad"),
//!                        ("a20105044101", b""), ("a20441010105", b"")]:
//!     encoded = (bytes.fromhex("84644d414330") + bstr(bytes.fromhex(protected))
//!                + bstr(aad) + bstr(payload))
//!     print(hmac.digest(key, encoded, hashlib.sha256).hex())
//! ```

use coset::{
    CborSerializable, CoseMac0, Header, ProtectedHeader, RegisteredLabelWithPrivate, iana,
};
use nazo_mdoc::{
    MdocError,
    device_auth::{verify_device_auth, verify_device_mac},
    model::DeviceAuth,
};

const KEY_HEX: &str = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f";
// Tag24(bstr(["DeviceAuthentication", [null, null, null], "test", Tag24(bstr({}))])).
const PAYLOAD_HEX: &str = concat!(
    "d8185823847444657669636541757468656e7469636174696f6e",
    "83f6f6f66474657374d81841a0",
);
const MAC_STRUCTURE_HEX: &str = concat!(
    "84644d41433043a10105405827",
    "d8185823847444657669636541757468656e7469636174696f6e",
    "83f6f6f66474657374d81841a0",
);
const TAG: &str = "8e61aa68d003dafbd1a92e7e6393fe6a348a1568f3bfc3d26bd0571c556364da";
const NONEMPTY_AAD_TAG: &str = "9c72a31ce133464e3e5f147b6045250d6632316299ec92ade8df29a7dab03243";
const PROTECTED_KID_TAG: &str = "4ffbf34e4cffcce2b3273bedb90681998462f6cbe95a342423912f19b62af175";
const REORDERED_PROTECTED_KID_TAG: &str =
    "9249617fb31ebae52622bf07e1e70855b56d8256ddfd523a397969357ffffbf8";

fn key() -> [u8; 32] {
    hex::decode(KEY_HEX).unwrap().try_into().unwrap()
}

fn payload() -> Vec<u8> {
    hex::decode(PAYLOAD_HEX).unwrap()
}

fn mac(protected_hex: &str, tag_hex: &str) -> CoseMac0 {
    let protected = hex::decode(protected_hex).unwrap();
    CoseMac0 {
        protected: ProtectedHeader {
            header: Header::from_slice(&protected).unwrap(),
            original_data: Some(protected),
        },
        unprotected: Header::default(),
        payload: None,
        tag: hex::decode(tag_hex).unwrap(),
    }
}

#[test]
fn python_hmac_sha256_vector_verifies_detached_mac0() {
    let mac0 = mac("a10105", TAG);
    let payload = payload();
    assert_eq!(
        coset::mac_structure_data(
            coset::MacContext::CoseMac0,
            mac0.protected.clone(),
            &[],
            &payload,
        ),
        hex::decode(MAC_STRUCTURE_HEX).unwrap()
    );
    let result = verify_device_mac(&mac0, &payload, &key()).unwrap();
    assert!(result.is_valid);
    assert!(result.reasons.is_empty());
    assert_eq!(result.algorithm, "HMAC256");
}

#[test]
fn device_mac_rejects_modified_and_wrong_length_tags() {
    let mut modified = mac("a10105", TAG);
    modified.tag[0] ^= 1;
    assert!(
        !verify_device_mac(&modified, &payload(), &key())
            .unwrap()
            .is_valid
    );
    for length in [0, 1, 16, 31] {
        let mut truncated = mac("a10105", TAG);
        truncated.tag.truncate(length);
        assert!(
            !verify_device_mac(&truncated, &payload(), &key())
                .unwrap()
                .is_valid,
            "tag length {length}"
        );
    }
    let mut extended = mac("a10105", TAG);
    extended.tag.push(0);
    assert!(
        !verify_device_mac(&extended, &payload(), &key())
            .unwrap()
            .is_valid
    );
}

#[test]
fn device_mac_requires_the_supplied_external_key() {
    let auth = DeviceAuth::Mac(mac("a10105", TAG));
    // This public key argument belongs to the signature arm. MAC callers must
    // supply an externally established EMacKey instead of deriving one here.
    let unused_signature_key = coset::CoseKey::default();
    assert!(matches!(
        verify_device_auth(&auth, &payload(), &unused_signature_key, None),
        Err(MdocError::DeviceAuth(_))
    ));
    assert!(
        verify_device_auth(&auth, &payload(), &unused_signature_key, Some(&key()))
            .unwrap()
            .is_valid
    );
    let mut wrong_key = key();
    wrong_key[0] ^= 1;
    assert!(
        !verify_device_auth(&auth, &payload(), &unused_signature_key, Some(&wrong_key))
            .unwrap()
            .is_valid
    );
}

#[test]
fn device_mac_authenticates_the_complete_original_payload() {
    let mac0 = mac("a10105", TAG);
    let original = payload();
    let mut changed = original.clone();
    let doctype = changed
        .windows(4)
        .position(|bytes| bytes == b"test")
        .unwrap();
    changed[doctype] ^= 1; // Same-length, valid CBOR text with a different docType.
    for altered in [changed.as_slice(), &original[4..], &[]] {
        // original[4..] removes Tag24+bstr and retains the inner array: hashing
        // only that inner representation must not authenticate the full payload.
        assert!(!verify_device_mac(&mac0, altered, &key()).unwrap().is_valid);
    }
}

#[test]
fn device_mac_requires_empty_external_aad() {
    // Same key, payload and protected headers as the passing vector, but this
    // independent tag authenticates external_aad = h'616164' ("aad").
    let mac0 = mac("a10105", NONEMPTY_AAD_TAG);
    assert!(
        !verify_device_mac(&mac0, &payload(), &key())
            .unwrap()
            .is_valid
    );
}

#[test]
fn device_mac_rejects_embedded_payloads() {
    for embedded in [payload(), vec![]] {
        let mut mac0 = mac("a10105", TAG);
        mac0.payload = Some(embedded);
        assert!(matches!(
            verify_device_mac(&mac0, &payload(), &key()),
            Err(MdocError::DeviceAuth(reason)) if reason.contains("detached payload")
        ));
    }
}

#[test]
fn device_mac_authenticates_original_protected_header_bytes() {
    let with_kid = mac("a20105044101", PROTECTED_KID_TAG);
    assert!(
        verify_device_mac(&with_kid, &payload(), &key())
            .unwrap()
            .is_valid
    );
    let reordered = mac("a20441010105", PROTECTED_KID_TAG);
    assert_eq!(with_kid.protected.header, reordered.protected.header);
    assert!(
        !verify_device_mac(&reordered, &payload(), &key())
            .unwrap()
            .is_valid
    );
    let matching_reordered_tag = mac("a20441010105", REORDERED_PROTECTED_KID_TAG);
    assert!(
        verify_device_mac(&matching_reordered_tag, &payload(), &key())
            .unwrap()
            .is_valid
    );
    let unsigned_added_kid = mac("a20105044101", TAG);
    assert!(
        !verify_device_mac(&unsigned_added_kid, &payload(), &key())
            .unwrap()
            .is_valid
    );
}

#[test]
fn device_mac_rejects_protected_header_metadata_mismatches() {
    let mut decoded_changed = mac("a10105", TAG);
    decoded_changed.protected.header.key_id = vec![1];
    assert!(matches!(
        verify_device_mac(&decoded_changed, &payload(), &key()),
        Err(MdocError::Cose(_))
    ));
    let mut raw_changed = mac("a10105", TAG);
    raw_changed.protected.original_data = Some(hex::decode("a20105044101").unwrap());
    assert!(matches!(
        verify_device_mac(&raw_changed, &payload(), &key()),
        Err(MdocError::Cose(_))
    ));
}

#[test]
fn device_mac_rejects_unsupported_or_unprotected_critical_headers() {
    for label in [
        RegisteredLabelWithPrivate::Assigned(iana::HeaderParameter::Kid),
        RegisteredLabelWithPrivate::PrivateUse(-65_537),
        RegisteredLabelWithPrivate::Text("future_security_extension".into()),
    ] {
        let mut mac0 = mac("a10105", TAG);
        mac0.protected.original_data = None;
        mac0.protected.header.crit.push(label);
        assert!(matches!(
            verify_device_mac(&mac0, &payload(), &key()),
            Err(MdocError::Cose(_))
        ));
    }
    let mut mac0 = mac("a10105", TAG);
    mac0.unprotected
        .crit
        .push(RegisteredLabelWithPrivate::Assigned(
            iana::HeaderParameter::Alg,
        ));
    assert!(matches!(
        verify_device_mac(&mac0, &payload(), &key()),
        Err(MdocError::Cose(_))
    ));
}
